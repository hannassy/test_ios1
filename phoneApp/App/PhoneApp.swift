// Когда пользователь нажимает на иконку, iOS читает эту структуру.
// @main — атрибут, который говорит Swift: «с этого файла начинается программа».
//
// В iOS-приложении нет функции main(). Вместо неё — структура, реализующая
// протокол App. Это соглашение SwiftUI: сам фреймворк вызывает нужный код.

import SwiftUI
import BackgroundTasks   // Фреймворк для фоновых задач (обновление графика ДТЭК)

@main
struct PhoneApp: App {

    // FeatureRegistry создаётся один раз при запуске и живёт всё время работы приложения.
    // «shared» — синглтон: единственный экземпляр в памяти.
    private let registry = FeatureRegistry.shared

    init() {
        // ───────────────────────────────────────────────────
        // РЕГИСТРАЦИЯ ФОНОВОЙ ЗАДАЧИ
        // ───────────────────────────────────────────────────
        // iOS сам решает, когда запустить приложение в фоне.
        // Мы только говорим: «если разбудишь нас с идентификатором
        // app.local.phoneapp.refresh — вызови вот этот код».
        //
        // Идентификатор задачи должен совпадать с тем, что записан
        // в Info.plist (BGTaskSchedulerPermittedIdentifiers).
        // Иначе iOS проигнорирует регистрацию.
        BGTaskScheduler.shared.register(
            forTaskWithIdentifier: "app.local.phoneapp.refresh",
            using: nil   // nil = выполнить на главном потоке диспетчера
        ) { task in
            // iOS передаёт объект BGTask — через него сообщаем, успешно ли завершилась задача.
            // Оборачиваем в Task { } чтобы использовать async/await внутри колбэка.
            Task { @MainActor in
                await BackgroundRefreshHandler.handleAppRefresh(task: task as! BGAppRefreshTask)
            }
        }
    }

    // ───────────────────────────────────────────────────────
    // СЦЕНА — ТО, ЧТО ВИДИТ ПОЛЬЗОВАТЕЛЬ
    // ───────────────────────────────────────────────────────
    // В SwiftUI «Scene» — это контейнер окна. На iPhone обычно одно окно.
    // WindowGroup создаёт стандартное окно приложения.
    // Внутри него — наш корневой экран RootMenuView.
    var body: some Scene {
        WindowGroup {
            // Передаём список функций из реестра.
            // RootMenuView не знает конкретных функций — только массив AppFeature.
            RootMenuView(features: registry.features)
        }
    }
}
