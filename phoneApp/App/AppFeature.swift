//
// Протокол в Swift — это набор требований, которым должен удовлетворять тип.
// Как интерфейс в других языках.
//
// Почему это важно для расширяемости:
//   Главное меню знает только этот протокол — не конкретные классы.
//   Чтобы добавить новый раздел, достаточно создать класс, реализующий AppFeature.
//   Существующий код при этом не трогается.
//
// Аналогия: розетка (протокол) не знает, что в неё воткнут — лампа или зарядка (функции).
//           Главное — чтобы вилка подходила.

import SwiftUI

// ───────────────────────────────────────────────────────────
// ИДЕНТИФИКАТОР ФУНКЦИИ
// ───────────────────────────────────────────────────────────
// typealias — псевдоним для существующего типа. Здесь String.
// Это читабельнее: пишем FeatureID вместо String, и сразу ясно назначение.
//
// Почему String, а не enum?
// Если бы был enum, то добавление нового пункта требовало бы редактировать
// этот файл (enum). Строка позволяет каждой функции задать свой id самостоятельно.
typealias FeatureID = String

// ───────────────────────────────────────────────────────────
// ПРОТОКОЛ ФУНКЦИИ
// ───────────────────────────────────────────────────────────
//
// @MainActor — все методы протокола вызываются на главном потоке.
// В iOS интерфейс можно обновлять только с главного потока (Main Thread).
// Это требование Apple. @MainActor автоматически гарантирует это.
//
// AnyObject — протокол могут реализовывать только классы (не структуры).
// Нужно потому, что функция живёт долго и хранит своё состояние.
@MainActor
protocol AppFeature: AnyObject {

    /// Уникальная строка-идентификатор. Используется для навигации и хранения состояния.
    /// Пример: "outages", "audiobooks", "debug".
    var id: FeatureID { get }

    /// Название пункта в главном меню. То, что видит пользователь.
    var title: String { get }

    /// Название иконки из коллекции SF Symbols.
    /// SF Symbols — бесплатная библиотека от Apple: bolt.fill, headphones, ladybug...
    /// Смотреть на сайте: https://developer.apple.com/sf-symbols/
    var symbolName: String { get }

    /// Возвращает корневой экран функции.
    ///
    /// AnyView — «обёртка», которая скрывает конкретный тип экрана.
    /// Меню не должно знать, что внутри — OutagesRootView или AudiobooksRootView.
    /// AnyView стирает этот тип, оставляя только View.
    func makeRootView() -> AnyView
}
